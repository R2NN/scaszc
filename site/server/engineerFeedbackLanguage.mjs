/** Write a short synthetic field account; totals and review decisions belong to the UI, not the engineer's voice. */
export function engineerVisitComment(visit, recentComments = []) {
  const delta = visit.total - visit.forecast.total;
  const direction = delta < 0 ? 'faster' : 'slower';
  const factors = visit.factors || visit.forecast.factors || {};
  const reason = visit.customerMinutes > 0 && visit.reason === 'unknown' ? 'customer' : visit.reason;
  let profile = accounts[reason] ? reason : visit.kind;
  if (['unknown', 'other'].includes(reason)) {
    profile = visit.kind === 'connection' && factors.line === 'existing' ? 'connectionExisting'
      : visit.kind === 'connection' && factors.line === 'new' ? 'connectionNew'
        : visit.kind === 'emergency' && factors.readyConfig ? 'emergencyReady' : visit.kind;
    // Large unexplained outliers must not acquire a convenient invented cause.
  }
  if (visit.reason === 'unknown' && delta > 60) profile = 'unrecorded';
  const messages = accounts[profile]?.[direction] || accounts[visit.kind]?.[direction] || accounts.information[direction];
  const code = parseInt(digest([visit.id, visit.engineerId]).slice(0, 8), 16);
  return Array.from({ length: messages.length }, (_, index) => messages[(code + index) % messages.length]).find(message => !recentComments.includes(message)) || messages[code % messages.length];
}
